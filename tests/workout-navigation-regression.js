// Evaluate in a disposable browser preview. Exercises the complete three-level flow.
(async () => {
  const originalState=gym.state,saved=localStorage.getItem(gym.KEY),originalId=gym.exerciseId;
  const originalAlert=window.alert,originalConfirm=window.confirm,originalSetItem=Storage.prototype.setItem;
  const settle=()=>new Promise(r=>setTimeout(r,30)),originalDsConfirm=ds.confirm;
  const failures=[];
  const check=(ok,message)=>{if(!ok)failures.push(message);};
  const click=selector=>document.querySelector(selector).click();
  const input=(selector,value)=>{const el=document.querySelector(selector);el.value=value;el.dispatchEvent(new Event('input',{bubbles:true}));};
  const open=(day,id)=>{gym.goWorkoutPage('workouts');click(`[data-action="openWorkout"][data-day="${day}"]`);click(`[data-action="openWorkoutExercise"][data-id="${id}"]`);};
  try{
    window.alert=()=>{};window.confirm=()=>true;ds.confirm=async()=>true;
    gym.state=gym.initial();gym.exerciseId=null;gym.update();
    check(document.querySelectorAll('[aria-label="Программа тренировок"] .workout-row').length===3,'Root must have A/B/C rows');
    check(!document.querySelector('#app .nav-back'),'Root must hide Back');
    click('[data-action="openWorkout"][data-day="A"]');
    check(document.querySelectorAll('.exercise-link').length===6,'Day A must list six exercises');
    check(!!document.querySelector('.navbar .nav-back'),'Day must show persistent Back');
    click('[data-action="done"][data-id="a2"]');
    check(!gym.exerciseId&&gym.state.done.A.includes('a2'),'Checkbox must mark done without opening exercise');
    click('[data-action="openWorkoutExercise"][data-id="a1"]');
    const before=gym.findExercise('incline').records.length;
    check(document.querySelectorAll('.ic-dot').length===before,'Exercise must show weight history immediately');
    check(!!document.querySelector('[data-action="startWorkoutExercise"]')&&!document.querySelector('#workoutSetsForm'),'Recording must start explicitly');
    click('[data-action="startWorkoutExercise"]');
    input('[data-set-field="weight"]','22,5');input('[data-set-field="reps"]','8');
    click('[data-action="addSet"]');
    check(document.querySelectorAll('.set-row').length===2,'Add must create a second set');
    input('.set-row:last-child [data-set-field="reps"]','7');
    click('[data-action="workoutBack"]');
    check(document.querySelector('.ex[data-id="a1"]').textContent.includes('В процессе'),'Day must show recording status');
    click('[data-action="openWorkoutExercise"][data-id="a1"]');
    check(document.querySelector('.set-row [data-set-field="weight"]').value==='22,5','Back and reopen must retain draft');
    check(JSON.parse(localStorage.getItem(gym.KEY)).sessions.A.a1.sets.length===2,'Draft sets must be persisted');
    input('.set-row:last-child [data-set-field="reps"]','0');
    document.getElementById('workoutSetsForm').requestSubmit();
    check(!!gym.exerciseId&&!gym.state.done.A.includes('a1')&&gym.findExercise('incline').records.length===before,'Invalid repetitions must not complete or write history');
    input('.set-row:last-child [data-set-field="reps"]','7');
    const storageBefore=localStorage.getItem(gym.KEY);
    Storage.prototype.setItem=function(key,value){if(key===gym.KEY)throw new DOMException('Full','QuotaExceededError');return originalSetItem.call(this,key,value);};
    document.getElementById('workoutSetsForm').requestSubmit();
    check(!!gym.exerciseId&&!gym.state.done.A.includes('a1')&&localStorage.getItem(gym.KEY)===storageBefore,'Failed save must preserve draft and stored records');
    Storage.prototype.setItem=originalSetItem;
    document.getElementById('workoutSetsForm').requestSubmit();
    check(!gym.exerciseId&&gym.state.tab==='A'&&gym.state.done.A.includes('a1'),'Save must mark done and return to day');
    check(gym.findExercise('incline').records.length===before+2&&gym.findExercise('incline').records.at(-1).weight===22.5,'Every set must appear in shared weight history');
    check(document.querySelector('.ex[data-id="a1"]').textContent.includes('Сохранено в'),'Row must show completion time');
    open('A','a1');click('[data-action="startWorkoutExercise"]');
    input('.set-row:first-child [data-set-field="weight"]','23');
    click('.set-row:last-child [data-action="removeSet"]');
    document.getElementById('workoutSetsForm').requestSubmit();
    check(gym.findExercise('incline').records.length===before+1&&gym.findExercise('incline').records.at(-1).weight===23,'Editing must replace this sessions records without duplicates');
    open('B','b2');check(!document.querySelector('.chart'),'Unlinked exercise must have empty history');
    click('[data-action="startWorkoutExercise"]');input('[data-set-field="weight"]','0');input('[data-set-field="reps"]','12');
    document.getElementById('workoutSetsForm').requestSubmit();
    check(!!gym.state.days.B[1].weightId&&gym.last(gym.findExercise(gym.state.days.B[1].weightId)).weight===0,'Unlinked bodyweight exercise must get a weight history');
    check(gym.state.sessions.A.a1.sets[0].weight===23,'Another day must not overwrite A session');
    gym.goWorkoutPage('A');click('[data-action="finish"]');await settle();
    check(gym.state.history[0].exercises[0].sets[0].weight===23&&!!gym.state.history[0].exercises[0].completedAt,'Workout history must snapshot sets and completion time');
    check(!gym.state.sessions.A.a1&&!!gym.state.sessions.B.b2,'Finish must clear only its own sessions');
    check(document.querySelector('.session-history').textContent.includes('23 кг'),'Archived sets must be readable');
    const snapshot=JSON.stringify(gym.state.history);
    open('A','a1');click('[data-action="startWorkoutExercise"]');gym.goWorkoutPage('A');click('[data-action="reset"]');await settle();
    check(!gym.state.sessions.A.a1&&JSON.stringify(gym.state.history)===snapshot,'Reset must clear drafts without changing history');
    const old=gym.initial();delete old.sessions;old.tab='B';old.done.B=['b1'];
    check(gym.prepareHistory(old).tab==='workouts'&&old.done.B.includes('b1')&&!!old.sessions,'Legacy backup must retain progress and open root');
    return {passed:!failures.length,failures};
  }finally{
    Storage.prototype.setItem=originalSetItem;window.alert=originalAlert;window.confirm=originalConfirm;ds.confirm=originalDsConfirm;
    gym.state=originalState;gym.exerciseId=originalId;gym.render();
    if(saved===null)localStorage.removeItem(gym.KEY);else localStorage.setItem(gym.KEY,saved);
  }
})()
